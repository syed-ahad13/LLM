"""Part B: prove that the fast trainer learns the reference trainer's merges on the 1 MB sample.

    python analysis/equivalence_1mb.py                     # -> docs/equivalence_1mb.md
    python analysis/equivalence_1mb.py --rerun-reference   # also time the reference trainer again here

Trains BPETokenizer.train (fast) on data/samples/train_1mb.txt for as many
merges as tokenizer/reference_1mb_3000.json holds (Step 7, train_reference),
and compares the two merge lists, and their pair counts, one by one. The
reference's wall-clock time comes from its meta (same machine, Step 7) unless
--rerun-reference trains it again in this process. Exits with status 1 if
the merges differ.
"""

import argparse
import sys
import time
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from bpe import BPETokenizer, count_words, token_display  # noqa: E402
from common import machine_info, setup_logging, sha256_file  # noqa: E402

DEFAULT_INPUT = ROOT / "data" / "samples" / "train_1mb.txt"
DEFAULT_REFERENCE = ROOT / "tokenizer" / "reference_1mb_3000.json"
DEFAULT_OUT = ROOT / "docs" / "equivalence_1mb.md"


def first_difference(a: Sequence[object], b: Sequence[object]) -> int | None:
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            return i
    return None if len(a) == len(b) else min(len(a), len(b))


def rel(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    p.add_argument("--reference", type=Path, default=DEFAULT_REFERENCE)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    p.add_argument("--rerun-reference", action="store_true", help="train the reference again and time it here")
    return p.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    log = setup_logging("equivalence_1mb")
    for path in (args.input, args.reference):
        if not path.exists():
            raise SystemExit(f"missing {path} (Step 7: clean/sample_1mb.py, train_tokenizer.py --trainer reference)")
    ref = BPETokenizer.load(args.reference)
    input_sha = sha256_file(args.input)
    if ref.meta.get("input_sha256") not in (None, input_sha):
        raise SystemExit(f"{args.reference} was trained on another file (sha256 {ref.meta['input_sha256']}); "
                         f"{args.input} has {input_sha}")
    n = len(ref.merges)
    vocab_size = ref.first_merge_id + n

    t0 = time.perf_counter()
    counts = count_words(args.input, workers=1)
    t1 = time.perf_counter()
    fast = BPETokenizer()
    summary = fast.train(counts, vocab_size, log_every=0)
    t2 = time.perf_counter()
    fast_seconds = t2 - t0
    log.info("fast: count_words %.2f s, train %.2f s", t1 - t0, t2 - t1)

    ref_seconds = ref.meta.get("train_seconds")
    ref_machine = (ref.meta.get("machine") or {}).get("cpu_model")
    rerun_same = None
    if args.rerun_reference:
        again = BPETokenizer()
        t3 = time.perf_counter()
        again.train_reference(args.input.read_text(encoding="utf-8"), vocab_size)
        ref_seconds = round(time.perf_counter() - t3, 2)
        ref_machine = machine_info()["cpu_model"]
        rerun_same = again.merges == ref.merges
        log.info("reference rerun: %.1f s, same merges as the file: %s", ref_seconds, rerun_same)

    diff = first_difference(fast.merges, ref.merges)
    same = diff is None
    counts_same = fast.merge_counts == ref.merge_counts if ref.merge_counts else None
    machine = machine_info()
    speedup = ref_seconds / fast_seconds if ref_seconds and fast_seconds else None
    lines = [
        "# Fast vs reference trainer on the 1 MB sample",
        "",
        "Generated by `python analysis/equivalence_1mb.py`"
        + (" --rerun-reference" if args.rerun_reference else "") + f" on {time.strftime('%Y-%m-%d %H:%M %Z')}.",
        "",
        f"**Result: {'IDENTICAL' if same else 'DIFFERENT'}.** The fast trainer (`BPETokenizer.train`) learned "
        f"{len(fast.merges):,} merges; the reference trainer (`BPETokenizer.train_reference`, "
        f"`{rel(args.reference)}`) learned {n:,}. "
        + ("Every merge is the same pair, in the same order"
           + (", with the same pair count." if counts_same else ".") if same
           else f"The first difference is at merge {diff + 1}."),
        "",
        "| | Value |",
        "|---|---|",
        f"| Input | `{rel(args.input)}`, {args.input.stat().st_size:,} bytes, sha256 `{input_sha[:16]}…` |",
        f"| Merges compared | {min(len(fast.merges), n):,} (vocab size {vocab_size:,}) |",
        f"| Identical merges | {'yes' if same else f'no, first difference at merge {diff + 1}'} |",
        f"| Identical pair counts | {'yes' if counts_same else 'no' if counts_same is False else 'not stored'} |",
        f"| Reference wall clock | {ref_seconds:,.1f} s ({'rerun here' if args.rerun_reference else 'Step 7 run'}; "
        f"{ref_machine}) |" if ref_seconds else "| Reference wall clock | not recorded |",
        f"| Fast wall clock | {fast_seconds:,.2f} s: count_words {t1 - t0:.2f} s + train {t2 - t1:.2f} s "
        f"({machine['cpu_model']}, Python {machine['python_version']}) |",
        f"| Speed-up | {speedup:,.0f}x |" if speedup else "| Speed-up | - |",
        f"| Distinct words | {summary['distinct_words']:,} (of {sum(counts.values()):,} word occurrences) |",
    ]
    if rerun_same is not None:
        lines.append(f"| Reference rerun equals the saved file | {'yes' if rerun_same else 'NO'} |")
    lines += ["", "The first 10 merges (both trainers):", "", "| Rank | Pair | Token | Count |", "|---:|---|---|---:|"]
    for i, (a, b) in enumerate(fast.merges[:10]):
        lines.append(f"| {i + 1} | ({a}, {b}) | `{token_display(fast.vocab[257 + i])}` | {fast.merge_counts[i]:,} |")
    if not same and diff is not None:
        lines += ["", "Around the first difference (fast / reference):", ""]
        for i in range(max(0, diff - 2), min(diff + 3, len(fast.merges), n)):
            lines.append(f"- merge {i + 1}: {fast.merges[i]} / {ref.merges[i]}")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {args.out}")
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
